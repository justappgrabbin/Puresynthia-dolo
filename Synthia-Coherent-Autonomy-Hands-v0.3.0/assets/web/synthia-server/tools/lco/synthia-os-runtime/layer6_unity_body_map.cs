    {
        Debug.Log($"Entering {center.cityName}...");

        // Load city scene
        // In production: load scene from WorldEngine JSON
        // For now: generate procedurally

        // Notify game manager
        GameManager.Instance?.LoadCity(center);
    }

    /**
     * Load body data from JSON.
     */
    public void LoadBodyDataFromJson(string json)
    {
        bodyData = JsonUtility.FromJson<BodyData>(json);

        // Clear and regenerate
        foreach (var center in centers.Values)
        {
            Destroy(center.gameObject);
        }
        centers.Clear();

        foreach (var channel in channels)
        {
            Destroy(channel.gameObject);
        }
        channels.Clear();

        GenerateBodyMap();
    }
}

