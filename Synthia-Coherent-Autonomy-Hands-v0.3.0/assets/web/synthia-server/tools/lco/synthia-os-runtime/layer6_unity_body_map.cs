// Genome agent
public class GenomeAgent : MonoBehaviour
{
    private BodyChannel channel;
    private float progress;
    private float speed;
    private Color color;

    public void Initialize(BodyChannel ch, Color col)
    {
        channel = ch;
        color = col;
        progress = Random.value;
        speed = Random.Range(0.1f, 0.5f);

        GetComponent<Renderer>().material.color = color;
    }

    public void UpdateMovement()
    {
        if (channel == null || channel.gameObject == null) return;

        progress += speed * Time.deltaTime;
        if (progress > 1f) progress = 0f;

        // Move along channel
        Vector3 start = channel.gameObject.transform.position - channel.gameObject.transform.forward * channel.gameObject.transform.localScale.z / 2f;
        Vector3 end = channel.gameObject.transform.position + channel.gameObject.transform.forward * channel.gameObject.transform.localScale.z / 2f;

        transform.position = Vector3.Lerp(start, end, progress);
    }
}

