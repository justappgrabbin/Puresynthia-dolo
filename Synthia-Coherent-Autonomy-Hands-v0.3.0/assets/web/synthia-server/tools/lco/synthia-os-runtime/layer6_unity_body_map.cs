using UnityEngine;
using System.Collections.Generic;
using System.Linq;

/**
 * SynthiaBodyMap - Unity Body Map Controller
 * ==========================================
 *
 * Renders the Human Design body chart as a navigable 3D world map.
 * Centers are cities. Channels are roads. Gates are buildings.
 * Genomes travel the roads. The player enters cities and plays scenarios.
 *
 * Attach this to a GameObject in Unity.
 */
public class SynthiaBodyMap : MonoBehaviour
{
    [Header("Body Map Settings")]
    public float bodyScale = 10f;
    public float centerSize = 1f;
    public float channelWidth = 0.1f;
    public float genomeSize = 0.2f;

    [Header("Center Positions (normalized 0-1)")]
    public Vector2 headPos = new Vector2(0.5f, 0.95f);
    public Vector2 ajnaPos = new Vector2(0.5f, 0.85f);
    public Vector2 throatPos = new Vector2(0.5f, 0.75f);
    public Vector2 gCenterPos = new Vector2(0.5f, 0.55f);
    public Vector2 egoPos = new Vector2(0.3f, 0.6f);
    public Vector2 sacralPos = new Vector2(0.5f, 0.4f);
    public Vector2 spleenPos = new Vector2(0.2f, 0.45f);
    public Vector2 solarPlexusPos = new Vector2(0.8f, 0.45f);
    public Vector2 rootPos = new Vector2(0.5f, 0.15f);

    [Header("Colors")]
    public Color definedColor = new Color(0.2f, 0.8f, 1f, 1f);
    public Color undefinedColor = new Color(0.3f, 0.3f, 0.4f, 0.5f);
    public Color channelActiveColor = new Color(0.2f, 0.5f, 1f, 0.8f);
    public Color channelInactiveColor = new Color(0.2f, 0.2f, 0.3f, 0.3f);
    public Color genomeColor = new Color(1f, 0.8f, 0.2f, 1f);

    [Header("Prefabs")]
    public GameObject centerPrefab;
    public GameObject channelPrefab;
    public GameObject genomePrefab;
    public GameObject gatePrefab;

    // Runtime data
    private Dictionary<string, BodyCenter> centers = new Dictionary<string, BodyCenter>();
    private List<BodyChannel> channels = new List<BodyChannel>();
    private List<GenomeAgent> genomes = new List<GenomeAgent>();
    private BodyData bodyData;

    void Start()
    {
        LoadBodyData();
        GenerateBodyMap();
        SpawnGenomes();
    }

    void Update()
    {
        UpdateGenomes();
        UpdateChannels();
    }

    /**
     * Load body data from JSON (generated by WorldEngine).
     */
    void LoadBodyData()
    {
        // In production: load from file or API
        // For now: create default data
        bodyData = new BodyData
        {
            userId = "user_001",
            definedCenters = new List<string> { "sacral", "throat", "g_center" },
            channels = new List<ChannelData>
            {
                new ChannelData { gateA = 1, gateB = 8, active = true },
                new ChannelData { gateA = 2, gateB = 14, active = true },
                new ChannelData { gateA = 3, gateB = 60, active = false }
            }
        };
    }

    /**
     * Generate the 3D body map.
     */
    void GenerateBodyMap()
    {
        // Create centers
        CreateCenter("head", headPos, "Head", "Crown City");
        CreateCenter("ajna", ajnaPos, "Ajna", "Mind City");
        CreateCenter("throat", throatPos, "Throat", "Voice City");
        CreateCenter("g_center", gCenterPos, "G-Center", "Identity City");
        CreateCenter("ego", egoPos, "Ego", "Will City");
        CreateCenter("sacral", sacralPos, "Sacral", "Life City");
        CreateCenter("spleen", spleenPos, "Spleen", "Instinct City");
        CreateCenter("solar_plexus", solarPlexusPos, "Solar Plexus", "Feeling City");
        CreateCenter("root", rootPos, "Root", "Pressure City");

        // Create channels
        foreach (var ch in bodyData.channels)
        {
            CreateChannel(ch);
        }

        // Create gates
        foreach (var center in centers.Values)
        {
            CreateGates(center);
        }
    }

    void CreateCenter(string id, Vector2 pos, string name, string cityName)
    {
        bool isDefined = bodyData.definedCenters.Contains(id);
        Vector3 worldPos = new Vector3(
            (pos.x - 0.5f) * bodyScale,
            (pos.y - 0.5f) * bodyScale,
            0
        );

        GameObject centerObj = Instantiate(centerPrefab, worldPos, Quaternion.identity, transform);
        centerObj.name = "Center_" + name;

        // Set visual properties
        Renderer renderer = centerObj.GetComponent<Renderer>();
        if (renderer != null)
        {
            renderer.material.color = isDefined ? definedColor : undefinedColor;
        }

        // Add glow for defined centers
        if (isDefined)
        {
            Light light = centerObj.AddComponent<Light>();
            light.type = LightType.Point;
            light.color = definedColor;
            light.intensity = 2f;
            light.range = 3f;
        }

        // Store center data
        centers[id] = new BodyCenter
        {
            id = id,
            name = name,
            cityName = cityName,
            position = worldPos,
            isDefined = isDefined,
            gameObject = centerObj
        };

        // Add click handler
        centerObj.AddComponent<CenterClickHandler>().Initialize(this, centers[id]);
    }

    void CreateChannel(ChannelData data)
    {
        // Find centers that contain these gates
        BodyCenter centerA = null;
        BodyCenter centerB = null;

        foreach (var center in centers.Values)
        {
            if (GateBelongsToCenter(data.gateA, center.id)) centerA = center;
            if (GateBelongsToCenter(data.gateB, center.id)) centerB = center;
        }

        if (centerA == null || centerB == null) return;

        // Create channel line
        Vector3 midPoint = (centerA.position + centerB.position) / 2f;
        float distance = Vector3.Distance(centerA.position, centerB.position);

        GameObject channelObj = Instantiate(channelPrefab, midPoint, Quaternion.identity, transform);
        channelObj.name = $"Channel_{data.gateA}_{data.gateB}";

        // Orient and scale
        channelObj.transform.LookAt(centerB.position);
        channelObj.transform.localScale = new Vector3(channelWidth, channelWidth, distance);

        // Set color
        Renderer renderer = channelObj.GetComponent<Renderer>();
        if (renderer != null)
        {
            renderer.material.color = data.active ? channelActiveColor : channelInactiveColor;
        }

        // Add particle system for active channels
        if (data.active)
        {
            ParticleSystem particles = channelObj.AddComponent<ParticleSystem>();
            var main = particles.main;
            main.startColor = channelActiveColor;
            main.startSize = 0.05f;
            main.startLifetime = 2f;
            main.startSpeed = 1f;
            main.maxParticles = 50;
        }

        channels.Add(new BodyChannel
        {
            gateA = data.gateA,
            gateB = data.gateB,
            active = data.active,
            gameObject = channelObj
        });
    }

    void CreateGates(BodyCenter center)
    {
        // Get gates for this center
        int[] gates = GetGatesForCenter(center.id);

        for (int i = 0; i < gates.Length; i++)
        {
            float angle = (i / (float)gates.Length) * Mathf.PI * 2f;
            float radius = centerSize * 1.5f;
            Vector3 gatePos = center.position + new Vector3(
                Mathf.Cos(angle) * radius,
                Mathf.Sin(angle) * radius,
                0
            );

            GameObject gateObj = Instantiate(gatePrefab, gatePos, Quaternion.identity, center.gameObject.transform);
            gateObj.name = $"Gate_{gates[i]}";

            // Add gate data
            GateData gateData = gateObj.AddComponent<GateData>();
            gateData.gateNumber = gates[i];
            gateData.center = center;
        }
    }

    void SpawnGenomes()
    {
        // Spawn genomes on active channels
        foreach (var channel in channels)
        {
            if (!channel.active) continue;

            for (int i = 0; i < 5; i++)
            {
                SpawnGenome(channel);
            }
        }
    }

    void SpawnGenome(BodyChannel channel)
    {
        GameObject genomeObj = Instantiate(genomePrefab, transform);
        genomeObj.name = "Genome_" + genomes.Count;

        GenomeAgent genome = genomeObj.AddComponent<GenomeAgent>();
        genome.Initialize(channel, genomeColor);
        genomes.Add(genome);
    }

    void UpdateGenomes()
    {
        foreach (var genome in genomes)
        {
            genome.UpdateMovement();
        }
    }

    void UpdateChannels()
    {
        // Pulse active channels
        foreach (var channel in channels)
        {
            if (channel.active && channel.gameObject != null)
            {
                Renderer renderer = channel.gameObject.GetComponent<Renderer>();
                if (renderer != null)
                {
                    float pulse = Mathf.Sin(Time.time * 2f) * 0.2f + 0.8f;
                    Color pulsedColor = channelActiveColor * pulse;
                    renderer.material.color = pulsedColor;
                }
            }
        }
    }

    // Helper methods
    bool GateBelongsToCenter(int gate, string centerId)
    {
        // Simplified gate-center mapping
        var gateMap = new Dictionary<string, int[]>
        {
            { "head", new[] { 64, 61, 63 } },
            { "ajna", new[] { 47, 24, 4, 11 } },
            { "throat", new[] { 56, 62, 23, 43, 20, 8, 31, 33, 12, 45 } },
            { "g_center", new[] { 1, 13, 25, 46, 2, 15, 10, 7, 44 } },
            { "ego", new[] { 51, 21, 26, 40 } },
            { "sacral", new[] { 5, 14, 29, 59, 9, 3, 42, 27, 34 } },
            { "spleen", new[] { 48, 18, 57, 28, 44, 50, 32 } },
            { "solar_plexus", new[] { 55, 30, 36, 22, 6, 37, 49, 63 } },
            { "root", new[] { 58, 38, 54, 19, 39, 41, 53, 60, 52 } }
        };

        if (gateMap.ContainsKey(centerId))
        {
            return gateMap[centerId].Contains(gate);
        }
        return false;
    }

    int[] GetGatesForCenter(string centerId)
    {
        var gateMap = new Dictionary<string, int[]>
        {
            { "head", new[] { 64, 61, 63 } },
            { "ajna", new[] { 47, 24, 4, 11 } },
            { "throat", new[] { 56, 62, 23, 43, 20, 8, 31, 33, 12, 45 } },
            { "g_center", new[] { 1, 13, 25, 46, 2, 15, 10, 7, 44 } },
            { "ego", new[] { 51, 21, 26, 40 } },
            { "sacral", new[] { 5, 14, 29, 59, 9, 3, 42, 27, 34 } },
            { "spleen", new[] { 48, 18, 57, 28, 44, 50, 32 } },
            { "solar_plexus", new[] { 55, 30, 36, 22, 6, 37, 49, 63 } },
            { "root", new[] { 58, 38, 54, 19, 39, 41, 53, 60, 52 } }
        };

        return gateMap.ContainsKey(centerId) ? gateMap[centerId] : new int[0];
    }

