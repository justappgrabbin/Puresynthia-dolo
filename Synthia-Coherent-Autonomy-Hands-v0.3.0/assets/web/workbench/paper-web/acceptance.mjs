import { chromium } from 'playwright-core';

const browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
const page = await browser.newPage({ acceptDownloads: true });
const evidence = [];
await page.goto('http://localhost:3000/', { waitUntil: 'networkidle' });
evidence.push(['initial empty state', await page.getByText('Import the deliberately broken fixture.').isVisible()]);
await page.getByRole('button', { name: /load broken fixture/i }).click();
await page.locator('.file-row').nth(2).waitFor();
evidence.push(['real ZIP import', (await page.locator('.file-row').count()) === 5]);
evidence.push(['AST/Mesh nodes', (await page.locator('.mesh-node').count()) >= 3]);
evidence.push(['canonical edges', /edges/.test(await page.locator('.stage-title').innerText())]);
evidence.push(['stable addresses', (await page.locator('.node-kind').allTextContents()).some((text) => /gate-\d+/.test(text))]);
evidence.push(['operator evidence', (await page.getByText(/evidence linked/i).count()) >= 3]);
await page.getByRole('button', { name: /run imported copy/i }).click();
await page.getByText('Failure captured', { exact: true }).waitFor();
evidence.push(['sandbox failure captured', await page.locator('.runtime-section').getByText(/PAPER_FAIL: deliberate fixture failure/i).isVisible()]);
evidence.push(['repair proposed', await page.getByText(/mutation ledger/i).isVisible()]);
await page.getByRole('button', { name: /^approve$/i }).click();
await page.getByRole('button', { name: /apply \+ validate/i }).click();
await page.locator('.proposal-section').getByText('COMMITTED', { exact: true }).last().waitFor();
const postRepairText = await page.locator('.proposal-card').innerText();
console.log('POST_REPAIR_STATE', postRepairText); console.log('POST_RUNTIME_STATE', await page.locator('.runtime-section').innerText());
evidence.push(['repair committed', /COMMITTED/.test(postRepairText)]);
evidence.push(['post-repair sandbox pass', await page.getByText('Entrypoint rendered', { exact: true }).isVisible()]);
await page.reload({ waitUntil: 'networkidle' });
evidence.push(['IndexedDB persistence', await page.getByText(/Restored project, Mesh, and recipe from IndexedDB/i).isVisible()]);
const downloadPromise = page.waitForEvent('download');
await page.getByRole('button', { name: /export repaired/i }).click();
const download = await downloadPromise;
evidence.push(['repaired export', download.suggestedFilename().endsWith('-repaired.zip')]);
const failed = evidence.filter(([, ok]) => !ok);
console.log(JSON.stringify({ passed: evidence.length - failed.length, total: evidence.length, evidence }, null, 2));
await browser.close();
if (failed.length) process.exit(1);
